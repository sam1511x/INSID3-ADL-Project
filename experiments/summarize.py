"""Collect all runs under output/ into markdown tables (results/SUMMARY.md).

Reads results.json written by the experiment scripts and log.txt written by the
original inference_segmentation.py / inference_keypoint_matching.py.

    python experiments/summarize.py --output-dir output --out results/SUMMARY.md
"""

import argparse
import ast
import glob
import json
import os
import re
from collections import defaultdict


def load_runs(output_dir):
    runs = []
    for d in sorted(glob.glob(os.path.join(output_dir, "*"))):
        rj = os.path.join(d, "results.json")
        lg = os.path.join(d, "log.txt")
        if os.path.isfile(rj):
            r = json.load(open(rj))
            r["run"] = os.path.basename(d)
            runs.append(r)
        elif os.path.isfile(lg):  # original INSID3 scripts
            text = open(lg).read().splitlines()
            if len(text) < 2:
                continue
            try:
                a = ast.literal_eval(text[1])
            except Exception:
                continue
            body = "\n".join(text[2:])
            m = re.search(r"mIoU = ([\d.]+)", body)
            p = re.findall(r"PCK@([\d.]+) = ([\d.]+)", body)
            if m:
                metrics = {"mIoU": float(m.group(1))}
                task, dataset = "segmentation", a["dataset"]
            elif p:
                metrics = {f"PCK@{t}": float(v) for t, v in p}
                task, dataset = "correspondence", "spair"
            else:
                continue
            label = "original script" + (" (debiased)" if a.get("debiased") else
                                         " (original feats)" if task == "correspondence" else "")
            runs.append({
                "run": os.path.basename(d), "task": task, "dataset": dataset, "fold": a["fold"],
                "shots": a["shots"], "model_size": a["model_size"], "image_size": a["image_size"],
                "svd_comps": a["svd_comps"], "crf": a.get("crf_mask_refinement", False),
                "episodes": "full", "complete": True, "peak_vram_gb": None,
                "variants": {label: metrics},
            })
    return runs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output-dir", default="output")
    ap.add_argument("--out", default="results/SUMMARY.md")
    ap.add_argument("--include-partial", action="store_true")
    a = ap.parse_args()

    runs = [r for r in load_runs(a.output_dir) if r.get("complete") or a.include_partial]
    groups = defaultdict(list)
    for r in runs:
        key = (r["task"], r["dataset"], r["shots"], r["model_size"], r["image_size"],
               r["svd_comps"], r["crf"], r["episodes"])
        groups[key].append(r)

    lines = ["# Results summary", "",
             "Generated by `experiments/summarize.py`. Each table: one benchmark/setting; "
             "columns = folds (and their mean).", ""]
    for key, rs in sorted(groups.items(), key=lambda kv: str(kv[0])):
        task, ds, shots, ms, im, k, crf, eps = key
        metric = "mIoU" if task == "segmentation" else "PCK@0.10"
        folds = sorted({r["fold"] for r in rs})
        table = defaultdict(dict)
        extra = defaultdict(dict)
        for r in rs:
            for label, v in r["variants"].items():
                if metric in v:
                    table[label][r["fold"]] = v[metric]
                    extra[label] = {kk: vv for kk, vv in v.items() if kk.startswith("PCK")}
        vram = max([r["peak_vram_gb"] or 0 for r in rs])
        lines.append(f"## {task} · {ds} · {shots}-shot · DINOv3-{ms} @ {im}px · k={k} · "
                     f"CRF={'on' if crf else 'off'} · episodes={eps} · peak VRAM {vram:.2f} GB")
        lines.append("")
        if task == "correspondence":
            cols = ["PCK@0.05", "PCK@0.10", "PCK@0.15", "PCK@0.20"]
            lines.append("| variant | " + " | ".join(cols) + " |")
            lines.append("|---|" + "---|" * len(cols))
            for label, v in extra.items():
                lines.append(f"| {label} | " + " | ".join(f"{v.get(c, float('nan')):.2f}" for c in cols) + " |")
        else:
            show_mean = len(folds) > 1
            hdr = [f"fold {f}" for f in folds] + (["mean"] if show_mean else [])
            lines.append(f"| variant ({metric}) | " + " | ".join(hdr) + " |")
            lines.append("|---|" + "---|" * len(hdr))
            for label, fv in table.items():
                cells = [f"{fv[f]:.2f}" if f in fv else "–" for f in folds]
                if show_mean:
                    cells.append(f"{sum(fv.values()) / len(fv):.2f}" if len(fv) == len(folds) else "–")
                lines.append(f"| {label} | " + " | ".join(cells) + " |")
        lines.append("")

    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    open(a.out, "w").write("\n".join(lines))
    print("\n".join(lines))
    print(f"\nwritten to {a.out}")


if __name__ == "__main__":
    main()
